/**
 * Synthetic demo study. Everything here is generated procedurally and clearly
 * labelled as synthetic; it contains no real study or partner data.
 */
import { makeDemoVessel, type TubeMesh } from '../geometry/tube';
import { formatImageName, positionsForSection, type Side } from './naming';
import { writeXlsx, type CellValue } from './spreadsheet';

export const DEMO_GROUPS = ['Control', 'Investigational device', 'Market standard'] as const;

function mulberry32(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function gauss(rand: () => number) {
  const u = Math.max(1e-12, rand());
  const v = rand();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

export interface DemoImageSpec {
  fileName: string;
  seed: number;
  damage: number;
  overlay: boolean;
}

export interface DemoStudy {
  mesh: TubeMesh;
  images: DemoImageSpec[];
  /** Spreadsheet rows: image name, magnification, % damage */
  rows: { name: string; damage: number }[];
  key: { vessel: string; treatment: string }[];
}

const SECTIONS = 4;
const MEDIAL = 2;

export function buildDemoStudy(): DemoStudy {
  const rand = mulberry32(240117);
  const vessels = Array.from({ length: 15 }, (_v, i) => `BRS24-${String(i + 1).padStart(2, '0')}`);
  const key = vessels.map((v, i) => ({ vessel: v, treatment: DEMO_GROUPS[i % 3] }));
  const base: Record<string, number> = { Control: 1.8, 'Investigational device': 5.4, 'Market standard': 8.6 };
  const images: DemoImageSpec[] = [];
  const rows: { name: string; damage: number }[] = [];
  const positions = positionsForSection(MEDIAL);
  const traced = new Set(['BRS24-02', 'BRS24-03', 'BRS24-05']);
  let seed = 1000;
  for (const { vessel, treatment } of key) {
    const vesselEffect = Math.exp(0.15 * gauss(rand));
    for (let s = 1; s <= SECTIONS; s++) {
      for (const side of ['T', 'B'] as Side[]) {
        positions.forEach((position, slot) => {
          seed++;
          // A little missing data, as in real studies.
          if (rand() < 0.035) return;
          if (vessel === 'BRS24-09' && s === 4 && side === 'B') return;
          const t = (s - 1 + (slot + 0.5) / positions.length) / SECTIONS;
          // Bends of the S-shaped vessel sit near 25% and 75% of its length.
          const bend = 1 + 0.8 * Math.exp(-(((t - 0.25) / 0.1) ** 2)) + 0.8 * Math.exp(-(((t - 0.75) / 0.1) ** 2));
          const sideEffect = side === 'B' ? 1.3 : 1;
          const noise = Math.exp(0.22 * gauss(rand));
          const extra = treatment === 'Market standard' && side === 'B' ? 1.15 : 1;
          const damage = Math.min(65, base[treatment] * vesselEffect * bend * sideEffect * noise * extra);
          const name = formatImageName({ bioreactor: vessel, magnification: '4x', section: s, side, position });
          const d = Math.round(damage * 100) / 100;
          images.push({ fileName: `${name}.jpg`, seed, damage: d, overlay: false });
          if (traced.has(vessel)) images.push({ fileName: `${name}_trace.png`, seed, damage: d, overlay: true });
          rows.push({ name, damage: d });
        });
      }
    }
  }
  // A few files that don't follow the naming convention (to demonstrate manual placement).
  const misnamed: [string, string][] = [
    ['BRS24-07_4x_3_T_M1', 'BRS24-07_4x_3_X_M1'],
    ['BRS24-12_4x_2_B_D', 'BRS24-12_4x_2_bottom'],
    ['BRS24-04_4x_1_T_P', 'IMG_2231'],
  ];
  for (const [good, bad] of misnamed) {
    const img = images.find((i) => i.fileName === `${good}.jpg`);
    const row = rows.find((r) => r.name === good);
    if (img) img.fileName = `${bad}.jpg`;
    if (row) row.name = bad;
  }
  return { mesh: makeDemoVessel(), images, rows, key };
}

export function demoWorkbook(study: DemoStudy): Uint8Array<ArrayBuffer> {
  const damage: CellValue[][] = [['Image', 'Magnification', '% Damage']];
  for (const r of study.rows) damage.push([r.name, '4x', r.damage]);
  const key: CellValue[][] = [['Bioreactor', 'Treatment']];
  for (const k of study.key) key.push([k.vessel, k.treatment]);
  return writeXlsx([
    { name: 'Damage', rows: damage },
    { name: 'Treatment key', rows: key },
    {
      name: 'About',
      rows: [
        ['Synthetic demo data generated by 3D Vessel Model.'],
        ['It does not contain any real study or partner data.'],
      ],
      freezeHeader: false,
    },
  ]);
}

// ── Synthetic "histology" images ────────────────────────────────────────────

const W = 800;
const H = 600;

function edgeY(x: number, phase: number, base: number, amp: number, period: number) {
  return base + amp * Math.sin(x / period + phase) + amp * 0.35 * Math.sin(x / (period * 0.37) + phase * 1.7);
}

export async function renderDemoImage(spec: DemoImageSpec, name: string): Promise<Blob> {
  const rand = mulberry32(spec.seed * 7919);
  const canvas = document.createElement('canvas');
  canvas.width = W;
  canvas.height = H;
  const ctx = canvas.getContext('2d')!;
  const ph1 = rand() * 6.28;
  const ph2 = rand() * 6.28;
  const top = (x: number) => edgeY(x, ph1, 205, 22, 95);
  const bottom = (x: number) => edgeY(x, ph2, 470, 18, 130);
  // Damage segments along the luminal (top) edge
  const totalLen = W * Math.min(0.92, spec.damage / 38 + 0.01);
  const segs: [number, number, number][] = [];
  let remaining = totalLen;
  let guard = 0;
  while (remaining > 8 && guard++ < 6) {
    const len = Math.min(remaining, 40 + rand() * Math.max(40, totalLen * 0.6));
    const start = rand() * (W - len);
    segs.push([start, start + len, 18 + rand() * 40 + spec.damage * 0.8]);
    remaining -= len;
  }
  const damagePath = () => {
    const p = new Path2D();
    for (const [a, b, depth] of segs) {
      p.moveTo(a, top(a));
      for (let x = a; x <= b; x += 6) p.lineTo(x, top(x) - 2);
      for (let x = b; x >= a; x -= 6) {
        const f = Math.sin(((x - a) / (b - a)) * Math.PI);
        p.lineTo(x, top(x) + depth * f * (0.75 + 0.25 * Math.sin(x * 0.11)));
      }
      p.closePath();
    }
    return p;
  };

  if (spec.overlay) {
    ctx.clearRect(0, 0, W, H);
    ctx.strokeStyle = '#ffd400';
    ctx.lineWidth = 4;
    ctx.lineJoin = 'round';
    ctx.stroke(damagePath());
    ctx.fillStyle = 'rgba(255, 212, 0, 0.18)';
    ctx.fill(damagePath());
  } else {
    ctx.fillStyle = '#f7f1f3';
    ctx.fillRect(0, 0, W, H);
    // Lumen: a few red blood cells
    for (let i = 0; i < 60; i++) {
      const x = rand() * W;
      const y = rand() * 150;
      ctx.fillStyle = `rgba(214, 94, 112, ${0.25 + rand() * 0.3})`;
      ctx.beginPath();
      ctx.ellipse(x, y, 5 + rand() * 3, 4 + rand() * 2, rand() * 3, 0, Math.PI * 2);
      ctx.fill();
    }
    // Tissue band
    const band = new Path2D();
    band.moveTo(0, top(0));
    for (let x = 0; x <= W; x += 8) band.lineTo(x, top(x));
    for (let x = W; x >= 0; x -= 8) band.lineTo(x, bottom(x));
    band.closePath();
    const grad = ctx.createLinearGradient(0, 180, 0, 500);
    grad.addColorStop(0, '#e9a3c0');
    grad.addColorStop(1, '#d784a9');
    ctx.fillStyle = grad;
    ctx.fill(band);
    ctx.save();
    ctx.clip(band);
    // Collagen fibres
    for (let i = 0; i < 140; i++) {
      const y0 = 180 + rand() * 320;
      ctx.strokeStyle = `rgba(160, 60, 105, ${0.12 + rand() * 0.18})`;
      ctx.lineWidth = 1 + rand() * 1.5;
      ctx.beginPath();
      const amp = 4 + rand() * 6;
      const per = 30 + rand() * 50;
      const ph = rand() * 6;
      for (let x = -10; x <= W + 10; x += 10) {
        const y = y0 + amp * Math.sin(x / per + ph);
        if (x === -10) ctx.moveTo(x, y);
        else ctx.lineTo(x, y);
      }
      ctx.stroke();
    }
    // Nuclei (denser along the luminal surface)
    for (let i = 0; i < 900; i++) {
      const x = rand() * W;
      const near = rand() < 0.35;
      const y = near ? top(x) + 3 + rand() * 14 : top(x) + rand() * (bottom(x) - top(x));
      ctx.fillStyle = `rgba(${70 + rand() * 30}, ${25 + rand() * 20}, ${100 + rand() * 30}, ${0.55 + rand() * 0.35})`;
      ctx.beginPath();
      ctx.ellipse(x, y, near ? 4.5 : 2 + rand() * 2.5, near ? 1.8 : 1.5 + rand() * 1.5, rand() * 3, 0, Math.PI * 2);
      ctx.fill();
    }
    ctx.restore();
    // Damaged regions: eroded, discoloured tissue
    const dp = damagePath();
    ctx.save();
    ctx.clip(band);
    ctx.fillStyle = 'rgba(122, 48, 86, 0.55)';
    ctx.fill(dp);
    ctx.clip(dp);
    for (let i = 0; i < 500; i++) {
      ctx.fillStyle = `rgba(${90 + rand() * 60}, ${20 + rand() * 30}, ${60 + rand() * 40}, ${0.3 + rand() * 0.4})`;
      ctx.fillRect(rand() * W, 150 + rand() * 200, 2 + rand() * 4, 2 + rand() * 4);
    }
    ctx.restore();
    // Scale bar and synthetic label
    ctx.fillStyle = '#1a1a19';
    ctx.fillRect(28, H - 40, 160, 7);
    ctx.font = '600 15px system-ui, sans-serif';
    ctx.fillText('500 µm', 28, H - 50);
    ctx.font = '600 14px system-ui, sans-serif';
    ctx.fillStyle = 'rgba(26,26,25,0.62)';
    ctx.textAlign = 'right';
    ctx.fillText(`SYNTHETIC DEMO IMAGE · ${name}`, W - 20, H - 22);
  }
  return new Promise((resolve, reject) =>
    canvas.toBlob(
      (b) => (b ? resolve(b) : reject(new Error('encode failed'))),
      spec.overlay ? 'image/png' : 'image/jpeg',
      0.88,
    ),
  );
}
